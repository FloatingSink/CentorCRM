const DICTIONARIES: Record<Locale, Record<string, string>> = { en, zh };

// `string & {}` keeps autocomplete on MessageKey while still accepting an
// arbitrary string. That is load-bearing, not laxness: zod messages in
// src/lib/validation/* are now keys, and an unknown key returns itself
// unchanged — so every action string not yet converted to a key keeps
// rendering its own English text verbatim while the rollout is part-done.
export function t(
  locale: Locale,
  key: MessageKey | (string & {}),
  vars?: Record<string, string | number>,
): string {
  const message = DICTIONARIES[locale][key] ?? key;
  if (!vars) return message;
  return message.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in vars ? String(vars[name]) : match,
  );
}

// English is the only locale here with a plural, and only ever two forms, so
// Intl.PluralRules would be a dependency-sized answer to a two-branch
// question.
export function tCount(
  locale: Locale,
  key: MessageKey | (string & {}),
  n: number,
): string {
  const suffix = locale === "en" && n === 1 ? "_one" : "_other";
  return t(locale, `${key}${suffix}`, { n });
}
